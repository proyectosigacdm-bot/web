-- =============================================================================
-- MIGRACIÓN: ROL INSPECTOR + CAMBIO DE ASISTENCIA
-- Motor: PostgreSQL (Neon)
-- =============================================================================
-- Esta migración habilita:
--   1. Nuevo rol 'INSPECTOR' en el enum de credenciales.
--   2. Tabla de perfil 'inspector' (misma estructura que administrador).
--   3. asistencia.id_docente nullable (el inspector NO es docente).
--   4. Trazabilidad de asistencia (quién creó / quién modificó).
--   5. Tabla de auditoría de asistencia (si no existe).
--   6. Usuario inspector de demostración: inspector@siga.cl / 1234
--
-- NOTA: ALTER TYPE ... ADD VALUE no puede ejecutarse dentro de una
-- transacción; ejecutar este script completo con psql o por statements
-- individuales.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. NUEVO ROL INSPECTOR
-- -----------------------------------------------------------------------------
ALTER TYPE rol_usuario_enum ADD VALUE IF NOT EXISTS 'INSPECTOR' AFTER 'APODERADO';

-- -----------------------------------------------------------------------------
-- 2. PERFIL INSPECTOR
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS inspector (
    id_inspector INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_credencial INTEGER NOT NULL UNIQUE REFERENCES credencial(id_credencial) ON DELETE RESTRICT,
    rut VARCHAR(12) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    telefono VARCHAR(20)
);

-- -----------------------------------------------------------------------------
-- 3. ASISTENCIA: permitir registros creados por INSPECTOR o ADMIN
--    (id_docente pasa a ser opcional)
-- -----------------------------------------------------------------------------
ALTER TABLE asistencia ALTER COLUMN id_docente DROP NOT NULL;

-- Trazabilidad: credencial que creó y que modificó cada registro
ALTER TABLE asistencia ADD COLUMN IF NOT EXISTS creado_por_credencial INTEGER REFERENCES credencial(id_credencial) ON DELETE SET NULL;
ALTER TABLE asistencia ADD COLUMN IF NOT EXISTS actualizado_por_credencial INTEGER REFERENCES credencial(id_credencial) ON DELETE SET NULL;

-- -----------------------------------------------------------------------------
-- 4. AUDITORÍA DE ASISTENCIA (por si la base aún no la tiene)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS asistencia_auditoria (
    id_auditoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asistencia INTEGER REFERENCES asistencia(id_asistencia) ON DELETE SET NULL,
    id_credencial INTEGER REFERENCES credencial(id_credencial) ON DELETE SET NULL,
    accion VARCHAR(30) NOT NULL CHECK (accion IN ('CREAR', 'ACTUALIZAR', 'ELIMINAR')),
    estado_anterior estado_asistencia_enum,
    estado_nuevo estado_asistencia_enum,
    detalle TEXT,
    realizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_asistencia_auditoria_asistencia ON asistencia_auditoria(id_asistencia);

